import nodemailer from "nodemailer";

function isConfigured() {
  if (process.env.RESEND_API_KEY) return true;
  if (process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASS) return true;
  return false;
}

async function createTransport() {
  if (process.env.RESEND_API_KEY) {
    return nodemailer.createTransport({
      host: "smtp.resend.com",
      port: 465,
      secure: true,
      auth: {
        user: "resend",
        pass: process.env.RESEND_API_KEY,
      },
    });
  }

  const port = Number(process.env.SMTP_PORT || 587);
  return nodemailer.createTransport({
    host: process.env.SMTP_HOST,
    port,
    secure: process.env.SMTP_SECURE === "true" || port === 465,
    auth: {
      user: process.env.SMTP_USER,
      pass: process.env.SMTP_PASS,
    },
  });
}

function escapeHtml(str = "") {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function buildEmailHtml({ roomId, summary, speakerPoints, transcript, sentBy }) {
  const bullets = summary?.bullets?.length
    ? summary.bullets.map((b) => `<li>${escapeHtml(b)}</li>`).join("")
    : "<li><em>No summary bullets yet — the meeting may still be in progress.</em></li>";

  const speakers = Object.entries(speakerPoints || {})
    .map(([speaker, points]) => {
      const items = (points || [])
        .slice(0, 8)
        .map((p) => `<li>${escapeHtml(p.text || p)}</li>`)
        .join("");
      return `<h3 style="color:#93c5fd;margin:20px 0 8px;font-size:15px;">${escapeHtml(speaker)}</h3><ul style="margin:0;padding-left:18px;color:#cbd5e1;line-height:1.6;">${items || "<li><em>No points yet</em></li>"}</ul>`;
    })
    .join("");

  const transcriptRows = (transcript || [])
    .slice(-40)
    .map(
      (line) =>
        `<tr><td style="padding:6px 10px;border-bottom:1px solid #1e293b;color:#94a3b8;white-space:nowrap;vertical-align:top;">${escapeHtml(line.speaker)}</td><td style="padding:6px 10px;border-bottom:1px solid #1e293b;color:#e2e8f0;">${escapeHtml(line.text)}</td></tr>`
    )
    .join("");

  return `<!DOCTYPE html>
<html>
<head><meta charset="utf-8" /></head>
<body style="margin:0;padding:0;background:#0a0e1a;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;">
  <div style="max-width:640px;margin:0 auto;padding:32px 20px;">
    <div style="background:linear-gradient(135deg,#111827,#0f172a);border:1px solid #1e293b;border-radius:16px;overflow:hidden;">
      <div style="padding:28px 28px 20px;border-bottom:1px solid #1e293b;">
        <div style="font-size:12px;letter-spacing:0.08em;text-transform:uppercase;color:#60a5fa;margin-bottom:8px;">Meet // Console</div>
        <h1 style="margin:0;font-size:22px;color:#f1f5f9;">Meeting Summary</h1>
        <p style="margin:8px 0 0;color:#94a3b8;font-size:14px;">Room <strong style="color:#e2e8f0;">${escapeHtml(roomId)}</strong>${sentBy ? ` · sent by ${escapeHtml(sentBy)}` : ""}</p>
      </div>
      <div style="padding:24px 28px;">
        <h2 style="margin:0 0 12px;font-size:16px;color:#f8fafc;">Key takeaways</h2>
        <ul style="margin:0;padding-left:18px;color:#cbd5e1;line-height:1.7;">${bullets}</ul>

        ${speakers ? `<div style="margin-top:28px;"><h2 style="margin:0 0 4px;font-size:16px;color:#f8fafc;">Speaker highlights</h2>${speakers}</div>` : ""}

        ${
          transcriptRows
            ? `<div style="margin-top:28px;">
          <h2 style="margin:0 0 12px;font-size:16px;color:#f8fafc;">Recent transcript</h2>
          <table style="width:100%;border-collapse:collapse;font-size:13px;">${transcriptRows}</table>
        </div>`
            : ""
        }
      </div>
      <div style="padding:16px 28px;border-top:1px solid #1e293b;color:#64748b;font-size:12px;">
        Generated by Meet // Console · ${new Date().toLocaleString()}
      </div>
    </div>
  </div>
</body>
</html>`;
}

function buildEmailText({ roomId, summary, speakerPoints, transcript, sentBy }) {
  const lines = [
    `Meet // Console — Meeting Summary`,
    `Room: ${roomId}`,
    sentBy ? `Sent by: ${sentBy}` : null,
    "",
    "KEY TAKEAWAYS",
    ...(summary?.bullets?.length ? summary.bullets.map((b) => `• ${b}`) : ["• No summary bullets yet"]),
    "",
  ].filter((x) => x !== null);

  for (const [speaker, points] of Object.entries(speakerPoints || {})) {
    lines.push(`SPEAKER: ${speaker}`);
    for (const p of (points || []).slice(0, 8)) {
      lines.push(`  - ${p.text || p}`);
    }
    lines.push("");
  }

  if (transcript?.length) {
    lines.push("RECENT TRANSCRIPT");
    for (const line of transcript.slice(-40)) {
      lines.push(`${line.speaker}: ${line.text}`);
    }
  }

  return lines.join("\n");
}

export async function sendMeetingSummaryEmail({
  to,
  roomId,
  summary,
  speakerPoints,
  transcript,
  sentBy,
}) {
  if (!isConfigured()) {
    const err = new Error(
      "Email is not configured. Set RESEND_API_KEY or SMTP_HOST/SMTP_USER/SMTP_PASS in backend/.env"
    );
    err.code = "EMAIL_NOT_CONFIGURED";
    throw err;
  }

  const from =
    process.env.EMAIL_FROM ||
    process.env.SMTP_USER ||
    "Meet Console <onboarding@resend.dev>";

  const transporter = await createTransport();
  const payload = { roomId, summary, speakerPoints, transcript, sentBy };

  const info = await transporter.sendMail({
    from,
    to,
    subject: `Meeting summary — ${roomId}`,
    text: buildEmailText(payload),
    html: buildEmailHtml(payload),
  });

  return { messageId: info.messageId, accepted: info.accepted };
}

export function emailStatus() {
  return {
    configured: isConfigured(),
    provider: process.env.RESEND_API_KEY
      ? "resend"
      : process.env.SMTP_HOST
        ? "smtp"
        : "none",
  };
}
